#!/usr/bin/env node
// Writes src/demo/overlay/ui/icons.ts: the Phosphor icons (phosphoricons.com, MIT) the overlay uses, as SVG markup.
// Phosphor is a dev dependency; the overlay ships only these. Add a name to ICONS and run `npm run icons`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Overlay name -> Phosphor file (assets/<weight>/<file>.svg). */
const ICONS = {
  play: "regular/play",
  next: "regular/arrow-right",
  check: "bold/check",
  done: "fill/check-circle",
  pending: "regular/circle",
  current: "regular/circle-dashed",
  box: "regular/square",
  boxChecked: "fill/check-square",
  chevronDown: "regular/caret-down",
  chevronUp: "regular/caret-up",
  chevronRight: "regular/caret-right",
  close: "regular/x",
  hide: "regular/eye-slash",
  show: "regular/eye",
  retry: "regular/arrow-clockwise",
  stop: "regular/stop",
  warning: "fill/warning",
  error: "fill/x-circle",
  info: "fill/info",
  zoom: "regular/magnifying-glass-plus",
  mobile: "regular/device-mobile",
  tablet: "regular/device-tablet",
  desktop: "regular/desktop",
  keyboard: "regular/keyboard",
  network: "regular/globe-simple",
  fastForward: "fill/fast-forward",
  terminal: "regular/terminal-window",
  copy: "regular/copy",
  checklist: "regular/list-checks",
  clock: "regular/clock",
  pointer: "fill/cursor",
  tap: "regular/hand-tap",
  sparkle: "regular/sparkle",
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "node_modules", "@phosphor-icons", "core", "assets");
const entries = Object.entries(ICONS).map(([name, file]) => {
  const [weight, base] = file.split("/");
  const svg = readFileSync(join(assets, weight, `${base}${weight === "regular" ? "" : `-${weight}`}.svg`), "utf8").trim();
  return `  ${name}: ${JSON.stringify(svg)},`;
});
writeFileSync(
  join(root, "src", "demo", "overlay", "ui", "icons.ts"),
  `// Generated by scripts/gen-icons.mjs - do not hand-edit. Icons: Phosphor (phosphoricons.com), MIT License,
// Copyright (c) 2023 Phosphor Icons.

/** The overlay's icons, as SVG markup (fill: currentColor). In the page: \`__wgIcon(name)\`. */
export const ICONS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`,
);
